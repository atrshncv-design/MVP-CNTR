/**
 * Единственный источник адреса API бэкенда (FE-02, истории R03/R03.1,
 * контракт URL-модуля в interfaces.md). Никакой другой код фронтенда не
 * вправе читать переменные адреса или вписывать хост самостоятельно.
 *
 * Почему так: продовый fallback зашивал адрес локальной машины разработчика
 * в клиентский бандл — запросы пользователей уходили на их собственную
 * собственную машину. Теперь браузер всегда ходит по относительному пути
 * того же origin (/api/v1/* проксируется rewrites из next.config.ts),
 * что упрощает CSP (connect-src 'self') и исключает mixed-content;
 * серверные вызовы (SSR, NextAuth) используют внутренний адрес из env.
 */

/**
 * База для браузерных вызовов: пустая строка — тот же origin
 * (fetch("/api/v1/...")), значение NEXT_PUBLIC_API_URL — опциональный
 * оверрайд для нестандартных схем развёртывания. Инлайнится при сборке.
 */
export const CLIENT_API_BASE: string = (
  process.env.NEXT_PUBLIC_API_URL?.trim() ?? ""
).replace(/\/+$/, "");

/**
 * Абсолютный внутренний адрес бэкенда для серверных вызовов (SSR-компоненты,
 * auth.config.ts). Не NEXT_PUBLIC_: читается в рантайме и не попадает в
 * клиентские бандлы. Отсутствие переменной — ошибка, а не fallback:
 * неполная конфигурация должна падать при сборке/старте с понятным
 * сообщением, а не молча отправлять данные на localhost.
 */
export function serverApiBase(): string {
  const raw = process.env.API_URL_INTERNAL?.trim();
  if (raw) return raw.replace(/\/+$/, "");
  throw new Error(
    "API_URL_INTERNAL не задан: серверным вызовам нужен явный внутренний адрес бэкенда. " +
      "Задайте переменную окружения (пример — .env.example); fallback на localhost в prod запрещён.",
  );
}
